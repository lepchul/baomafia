def profile(name: str, stats: dict, inventory: dict[str, int]) -> str:
    inv = (
        "\n".join(
            f"{SHOP_ITEMS[k]['emoji']} {SHOP_ITEMS[k]['title']} — {v} шт."
            for k, v in inventory.items()
            if k in SHOP_ITEMS
        )
        or "пусто"
    )
    return (
        f"👤 <b>{name}</b>\n\n"
        f"Баланс: {stats['balance']} {CURRENCY}\n"
        f"Игр: {stats['games']}\n"
        f"Побед: {stats['wins']}\n\n"
        f"<b>Инвентарь:</b>\n{inv}"
    )
